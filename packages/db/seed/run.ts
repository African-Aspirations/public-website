/**
 * Seed the database with the content transcribed from the legacy site.
 *
 *   bun seed/run.ts --check             # validate everything + write seed/REVIEW.md, no DB
 *   DATABASE_MIGRATION_URL=… bun seed/run.ts           # seed an empty database
 *   DATABASE_MIGRATION_URL=… bun seed/run.ts --force   # replace existing CONTENT (never leads/staff/listings)
 *
 * Media rows use the same deterministic Cloudinary public_id the asset
 * migration uploads to, with dimensions read from the local legacy file, so
 * seeding does not have to wait for the upload (it warns if not uploaded yet).
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { extname, join, resolve as resolvePath } from "node:path";
import { sql } from "drizzle-orm";
import { drizzle } from "drizzle-orm/postgres-js";
import postgres from "postgres";
import sharp from "sharp";
import * as s from "../src/schema";
import { type SectionType, sectionSchemas } from "../src/sections";
import { content } from "./content";
import type { Manifest } from "./migrate-assets";
import { publicIdFor } from "./migrate-assets";
import type { AssetRef, RowRef, SeedNavItem, SeedPage } from "./types";
import { collectAssets, resolve } from "./walk";

const args = new Set(process.argv.slice(2));
const LEGACY_PUBLIC = resolvePath(
  process.env.LEGACY_PUBLIC ?? join(import.meta.dirname, "../../../../aa-website-legacy/public"),
);
const MANIFEST = resolvePath(import.meta.dirname, "assets.manifest.json");

// ---------- validation (no DB) ----------
function validate(): string[] {
  const errors: string[] = [];
  const slugs = new Set<string>();
  const fakeId = "00000000-0000-4000-8000-000000000000";
  const knownRefs = {
    partner: new Set(content.partners.map((p) => p.key)),
    team: new Set(content.teamMembers.map((t) => t.key)),
    service: new Set(content.services.map((x) => x.key)),
    page: new Set(content.pages.map((p) => p.slug)),
  };

  for (const page of content.pages) {
    const where = `page "${page.slug || "(home)"}"`;
    if (slugs.has(page.slug)) errors.push(`${where}: duplicate slug`);
    slugs.add(page.slug);
    if (page.sections[0]?.type !== "hero") errors.push(`${where}: first section must be a hero`);
    for (const [i, sec] of page.sections.entries()) {
      const data = resolve(
        sec.data,
        () => fakeId,
        (r: RowRef) => {
          if (!knownRefs[r.$ref].has(r.key))
            errors.push(`${where} section ${i}: unknown ref ${r.$ref}:${r.key}`);
          return fakeId;
        },
      );
      const schema = sectionSchemas[sec.type as SectionType];
      if (!schema) {
        errors.push(`${where} section ${i}: unknown type ${sec.type}`);
        continue;
      }
      const r = schema.safeParse(data);
      if (!r.success)
        errors.push(
          `${where} section ${i} (${sec.type}): ${r.error.issues.map((x) => `${x.path.join(".")}: ${x.message}`).join("; ")}`,
        );
    }
  }

  const linkSlugs = (items: SeedNavItem[]): string[] =>
    items.flatMap((n) => [
      ...(n.pageSlug !== undefined ? [n.pageSlug] : []),
      ...linkSlugs(n.children ?? []),
    ]);
  for (const slug of [
    ...linkSlugs(content.nav.header),
    ...Object.values(content.nav.footer).flatMap(linkSlugs),
    ...linkSlugs(content.nav.legal),
  ]) {
    if (!knownRefs.page.has(slug)) errors.push(`nav: links to unknown page "${slug}"`);
  }
  for (const svc of content.services) {
    if (svc.pageSlug !== undefined && !knownRefs.page.has(svc.pageSlug))
      errors.push(`service ${svc.key}: unknown page ${svc.pageSlug}`);
  }
  if (existsSync(LEGACY_PUBLIC)) {
    for (const [path] of collectAssets(content)) {
      if (!existsSync(join(LEGACY_PUBLIC, path))) errors.push(`asset missing on disk: ${path}`);
    }
  } else {
    console.warn(`(legacy public/ not found at ${LEGACY_PUBLIC}; skipping image file checks)`);
  }
  return errors;
}

function writeReview() {
  const lines = [
    "# Content review checklist",
    "",
    "Generated by `bun seed/run.ts --check` from the `review` notes in seed/content.",
    "Everything here was found while moving the legacy copy into the database. Fix it in the admin (or in the seed before first launch).",
    "",
  ];
  for (const p of content.pages as SeedPage[]) {
    if (!p.review?.length) continue;
    lines.push(
      `## /${p.slug}${p.status === "draft" ? " (draft)" : ""}`,
      "",
      ...p.review.map((r) => `- [ ] ${r}`),
      "",
    );
  }
  writeFileSync(join(import.meta.dirname, "REVIEW.md"), `${lines.join("\n").trimEnd()}\n`);
}

// ---------- seeding ----------
async function seed(url: string) {
  const client = postgres(url, { prepare: false, onnotice: () => {} });
  const db = drizzle(client, { schema: s });
  const manifest: Manifest = existsSync(MANIFEST) ? JSON.parse(readFileSync(MANIFEST, "utf8")) : {};

  await db.transaction(async (tx) => {
    const [{ n } = { n: 0 }] = await tx.select({ n: sql<number>`count(*)::int` }).from(s.pages);
    if (n > 0 && !args.has("--force"))
      throw new Error(`Database already has ${n} pages. Use --force to replace content.`);
    if (n > 0) {
      // Content only. Media rows are upserted (listings may point at them); leads, staff, listings untouched.
      await tx.execute(
        sql`TRUNCATE nav_items, page_sections, service_features, services, team_members, partners, faqs, redirects, site_settings, pages RESTART IDENTITY CASCADE`,
      );
    }

    // media
    const mediaIds = new Map<string, string>();
    let notUploaded = 0;
    for (const [path, alt] of collectAssets(content)) {
      const file = join(LEGACY_PUBLIC, path);
      const up = manifest[path];
      // Dimensions: from the upload manifest, else the local legacy file. In CI (no legacy
      // files, nothing uploaded yet) --allow-missing-images uses a 4:3 stand-in.
      const meta: { width?: number; height?: number; format?: string } = up
        ? {}
        : existsSync(file)
          ? await sharp(file).metadata()
          : args.has("--allow-missing-images")
            ? { width: 1600, height: 1200 }
            : fail(`legacy image not found: ${file} (pass --allow-missing-images in CI)`);
      if (!up) notUploaded++;
      const publicId = up?.publicId ?? publicIdFor(path, alt);
      const [row] = await tx
        .insert(s.media)
        .values({
          publicId,
          width: up?.width || meta.width || 0,
          height: up?.height || meta.height || 0,
          format: up?.format || meta.format || extname(path).slice(1),
          alt,
        })
        .onConflictDoUpdate({ target: s.media.publicId, set: { alt } })
        .returning({ id: s.media.id });
      if (row) mediaIds.set(path, row.id);
    }
    const mediaId = (a: AssetRef) => mediaIds.get(a.$asset) ?? fail(`no media for ${a.$asset}`);

    // rows that sections/nav can reference
    const ids = {
      partner: new Map<string, string>(),
      team: new Map<string, string>(),
      service: new Map<string, string>(),
      page: new Map<string, string>(),
    };
    const rowId = (r: RowRef) =>
      ids[r.$ref].get(r.key) ?? fail(`unresolved ref ${r.$ref}:${r.key}`);

    for (const [i, p] of content.partners.entries()) {
      const [row] = await tx
        .insert(s.partners)
        .values({
          name: p.name,
          description: p.description,
          url: p.url,
          logoId: p.logo && mediaId(p.logo),
          stats: p.stats,
          sortOrder: i,
          status: "published",
        })
        .returning({ id: s.partners.id });
      ids.partner.set(p.key, must(row).id);
    }
    for (const [i, t] of content.teamMembers.entries()) {
      const [row] = await tx
        .insert(s.teamMembers)
        .values({
          name: t.name,
          role: t.role,
          credentials: t.credentials,
          summary: t.summary,
          bio: t.bio,
          photoId: t.photo && mediaId(t.photo),
          linkedinUrl: t.linkedinUrl,
          sortOrder: i,
          status: "published",
        })
        .returning({ id: s.teamMembers.id });
      ids.team.set(t.key, must(row).id);
    }
    for (const p of content.pages as SeedPage[]) {
      const [row] = await tx
        .insert(s.pages)
        .values({
          slug: p.slug,
          title: p.title,
          template: p.template ?? (p.slug === "" ? "home" : "default"),
          seoTitle: p.seoTitle,
          seoDescription: p.seoDescription,
          status: p.status ?? "published",
          noindex: p.noindex ?? false,
        })
        .returning({ id: s.pages.id });
      ids.page.set(p.slug, must(row).id);
    }
    for (const p of content.pages as SeedPage[]) {
      for (const [i, sec] of p.sections.entries()) {
        const data = sectionSchemas[sec.type].parse(resolve(sec.data, mediaId, rowId));
        await tx
          .insert(s.pageSections)
          .values({ pageId: must(ids.page.get(p.slug)), type: sec.type, data, sortOrder: i });
      }
      for (const from of p.legacyPaths ?? []) {
        await tx
          .insert(s.redirects)
          .values({ fromPath: from, toPath: `/${p.slug}`, statusCode: 301 });
      }
    }
    for (const [i, svc] of content.services.entries()) {
      const [row] = await tx
        .insert(s.services)
        .values({
          slug: svc.key,
          title: svc.title,
          summary: svc.summary,
          imageId: svc.image && mediaId(svc.image),
          pageId: svc.pageSlug !== undefined ? ids.page.get(svc.pageSlug) : undefined,
          sortOrder: i,
          status: "published",
        })
        .returning({ id: s.services.id });
      ids.service.set(svc.key, must(row).id);
      for (const [j, f] of (svc.features ?? []).entries()) {
        await tx.insert(s.serviceFeatures).values({
          serviceId: must(row).id,
          title: f.title,
          description: f.description,
          sortOrder: j,
        });
      }
    }
    for (const svc of content.services) {
      const parent = svc.parentKey && ids.service.get(svc.parentKey);
      if (parent)
        await tx
          .update(s.services)
          .set({ parentId: parent })
          .where(sql`${s.services.slug} = ${svc.key}`);
    }

    const st = content.siteSettings;
    await tx.insert(s.siteSettings).values({
      id: 1,
      orgName: st.orgName,
      tagline: st.tagline,
      address: st.address,
      phone: st.phone,
      email: st.email,
      socials: st.socials,
      defaultSeoTitle: st.defaultSeoTitle,
      defaultSeoDescription: st.defaultSeoDescription,
      logoId: st.logo && mediaId(st.logo),
      ctaLabel: st.ctaLabel,
      ctaUrl: st.ctaUrl,
    });

    // `base` offsets sort_order so footer columns keep their order (columns are ordered by
    // their first item's sort_order).
    const insertNav = async (
      menu: string,
      items: SeedNavItem[],
      parentId: string | null,
      base = 0,
    ) => {
      for (const [i, item] of items.entries()) {
        const [row] = await tx
          .insert(s.navItems)
          .values({
            menu,
            parentId,
            label: item.label,
            description: item.description,
            pageId: item.pageSlug !== undefined ? ids.page.get(item.pageSlug) : undefined,
            url: item.url,
            sortOrder: base + i,
          })
          .returning({ id: s.navItems.id });
        await insertNav(menu, item.children ?? [], must(row).id);
      }
    };
    await insertNav("header", content.nav.header, null);
    for (const [c, [column, items]] of Object.entries(content.nav.footer).entries())
      await insertNav(`footer:${column}`, items, null, c * 100);
    await insertNav("legal", content.nav.legal, null);

    console.log(
      `Seeded ${content.pages.length} pages, ${content.services.length} services, ${content.teamMembers.length} team members, ${mediaIds.size} media.`,
    );
    if (notUploaded)
      console.warn(
        `⚠ ${notUploaded} image(s) not uploaded to Cloudinary yet — run seed/migrate-assets.ts.`,
      );
  });
  await client.end();
}

function fail(msg: string): never {
  throw new Error(msg);
}
function must<T>(v: T | undefined): T {
  return v ?? fail("expected a row");
}

const errors = validate();
writeReview();
if (errors.length) {
  console.error(`✗ ${errors.length} seed error(s):\n${errors.map((e) => `  - ${e}`).join("\n")}`);
  process.exit(1);
}
console.log("✓ Seed content is valid. Review checklist written to seed/REVIEW.md");
if (!args.has("--check")) {
  const url = process.env.DATABASE_MIGRATION_URL;
  if (!url) fail("Set DATABASE_MIGRATION_URL (owner connection) to seed.");
  await seed(url);
}
